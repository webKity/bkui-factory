import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';

const root = new URL('../', import.meta.url);
const source = JSON.parse(await readFile(new URL('source/icons/figma-icons.json', root), 'utf8'));
const overrides = {
  '169:1468': 'ellipsis-vertical', '169:1648': 'arrow-up-to-line',
  '169:2134': 'expand-fullscreen', '169:2209': 'filter-horizontal',
  '474:114': 'passkey', '169:2566': 'layout-single',
  '169:2571': 'layout-columns-2', '169:2576': 'layout-rows-2',
  '169:2581': 'layout-columns-3', '169:2586': 'layout-rows-3',
  '169:2591': 'layout-columns-4', '169:2596': 'layout-rows-4',
  '169:2601': 'layout-grid', '169:2606': 'fullscreen',
};
const groups = new Map();
const usedNames = new Set();
for (const icon of source.icons) {
  let group = groups.get(icon.groupId);
  if (!group) {
    const base = overrides[icon.groupId] ?? icon.groupName.match(/^[a-zA-Z0-9 -]+/)?.[0].trim().toLowerCase().replace(/\s+/g, '-');
    if (!base) throw new Error(`Missing name: ${icon.groupName}`);
    let name = base;
    for (let suffix = 2; usedNames.has(name); suffix++) name = `${base}-${suffix}`;
    usedNames.add(name);
    group = { name, label: icon.groupName, groupId: icon.groupId };
    groups.set(icon.groupId, group);
  }
  if (!['regular', 'filled'].includes(icon.variant) || group[icon.variant]) throw new Error(`Duplicate variant: ${icon.nodeId}`);
  const dom = new JSDOM(icon.svg, { contentType: 'image/svg+xml' });
  const svg = dom.window.document.documentElement;
  if (svg.tagName !== 'svg' || !svg.getAttribute('viewBox')) throw new Error(`Invalid SVG: ${icon.nodeId}`);
  const paths = [...svg.children].map(path => {
    if (path.tagName !== 'path') throw new Error(`Unsupported element: ${path.tagName}`);
    const attrs = {};
    for (const {name, value} of path.attributes) {
      if (!['d', 'fill', 'fill-rule', 'clip-rule'].includes(name)) throw new Error(`Unsupported attribute: ${name}`);
      const prop = { 'fill-rule': 'fillRule', 'clip-rule': 'clipRule' }[name] ?? name;
      attrs[prop] = name === 'fill' && value === 'black' ? 'currentColor' : value;
    }
    if (!attrs.d) throw new Error(`Empty path: ${icon.nodeId}`);
    return attrs;
  });
  group[icon.variant] = { nodeId: icon.nodeId, viewBox: svg.getAttribute('viewBox'), paths };
  dom.window.close();
}
for (const group of groups.values()) {
  if (!group.regular || !group.filled) throw new Error(`Incomplete variants: ${group.name}`);
}
const definitions = Object.fromEntries([...groups.values()].map(({ name, ...value }) => [name, value]));
const output = `// Generated by scripts/generate-icons.mjs from the original Figma SVG exports.\n// Do not edit: update source/icons/figma-icons.json and regenerate.\nexport const figmaIcons = ${JSON.stringify(definitions, null, 2)} as const;\n\nexport type FigmaIconName = keyof typeof figmaIcons;\nexport type IconVariant = 'regular' | 'filled';\nexport const figmaIconNames = Object.keys(figmaIcons) as FigmaIconName[];\n`;
const target = new URL('packages/assets/src/icons/figma.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Generated icons are stale; run npm run icons:build');
} else {
  await writeFile(target, output);
}
console.log(`${groups.size} groups / ${source.icons.length} SVGs ${process.argv.includes('--check') ? 'verified' : `generated: ${fileURLToPath(target)}`}`);
