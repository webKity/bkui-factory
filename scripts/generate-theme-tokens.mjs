import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const defaultSourceDir = path.join(projectRoot, 'source');
const defaultTargetDir = path.join(projectRoot, 'src/components/themes');
const generatedNotice = 'Generated by npm run tokens:build; do not edit.';
const fontModes = new Map([['English', 'en'], ['中文', 'zh'], ['Numeric', 'numeric']]);
const pixelScopes = new Set(['FONT_SIZE', 'LINE_HEIGHT', 'LETTER_SPACING', 'CORNER_RADIUS']);

function normalizeName(value) {
  const name = value.trim().replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s/_.]+/g, '-').toLowerCase();
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`无法转换变量或目录名称：${JSON.stringify(value)}`);
  }
  return name;
}

async function findFiles(directory, suffix, allowMissing = false) {
  const entries = await readdir(directory, { withFileTypes: true }).catch(error => {
    if (allowMissing && error.code === 'ENOENT') return [];
    throw error;
  });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await findFiles(fullPath, suffix));
    else if (entry.isFile() && entry.name.trim().endsWith(suffix)) files.push(fullPath);
  }
  return files;
}

function parseSourcePath(relativePath) {
  const parts = relativePath.split(path.sep);
  const collection = parts[0].trim();
  if (!['primitives', 'semantic'].includes(collection) || ![2, 3].includes(parts.length)) {
    throw new Error('文件路径应为 primitives/<theme>/<name>.tokens.json 或 semantic/[<theme>/]<name>.tokens.json');
  }
  const sourceName = parts.at(-1).trim().slice(0, -'.tokens.json'.length);
  const isTypography = collection === 'semantic' && fontModes.has(sourceName);
  const isRadius = collection === 'semantic' && sourceName === 'radius';
  if (parts.length === 2 && !isTypography && !isRadius) throw new Error('只有字体模式和圆角文件可以不指定主题');
  return {
    relativePath,
    kind: isTypography ? 'typography' : isRadius ? 'radius' : collection === 'primitives' ? 'primitive' : 'semantic',
    theme: parts.length === 3 ? normalizeName(parts[1]) : null,
    name: isTypography ? fontModes.get(sourceName) : normalizeName(sourceName),
  };
}

function collectTokens(group, names = [], inheritedType, tokens = []) {
  if (!group || typeof group !== 'object' || Array.isArray(group)) {
    throw new Error(`无效的变量分组：${names.join('.')}`);
  }
  const type = group.$type ?? inheritedType;
  if (Object.hasOwn(group, '$value')) {
    if (!names.length) throw new Error('变量必须有名称');
    tokens.push({
      name: names.map(normalizeName).join('-'),
      type,
      value: group.$value,
      scopes: group.$extensions?.['com.figma.scopes'] ?? [],
      alias: group.$extensions?.['com.figma.aliasData'],
    });
  } else {
    for (const [name, child] of Object.entries(group)) {
      if (!name.startsWith('$')) collectTokens(child, [...names, name], type, tokens);
    }
  }
  return tokens;
}

function colorToCss(value) {
  if (typeof value === 'string' && /^#[\da-f]{6}([\da-f]{2})?$/i.test(value)) return value.toUpperCase();
  if (!value || typeof value !== 'object' || value.colorSpace !== 'srgb') {
    throw new Error('颜色必须是十六进制颜色或 Figma srgb 颜色对象');
  }
  const alpha = value.alpha ?? 1;
  if (!Number.isFinite(alpha) || alpha < 0 || alpha > 1) throw new Error('颜色 alpha 必须介于 0 和 1 之间');
  let hex = value.hex;
  if (hex !== undefined && !/^#[\da-f]{6}$/i.test(hex)) throw new Error(`无效的颜色 hex：${hex}`);
  if (hex === undefined) {
    if (!Array.isArray(value.components) || value.components.length !== 3 ||
        value.components.some(channel => !Number.isFinite(channel) || channel < 0 || channel > 1)) {
      throw new Error('srgb components 必须包含三个介于 0 和 1 之间的数字');
    }
    hex = `#${value.components.map(channel => Math.round(channel * 255).toString(16).padStart(2, '0')).join('')}`;
  }
  return `${hex}${alpha === 1 ? '' : Math.round(alpha * 255).toString(16).padStart(2, '0')}`.toUpperCase();
}

function scalarToCss(token) {
  if (token.type === 'string' && typeof token.value === 'string') {
    // CSS 字符串的换行转义与 JSON 不同。
    return `"${token.value.replace(/["\\\n\r\f]/g, char => ({
      '"': '\\"', '\\': '\\\\', '\n': '\\a ', '\r': '\\d ', '\f': '\\c ',
    })[char])}"`;
  }
  if (token.type === 'number' && Number.isFinite(token.value)) {
    return `${token.value}${token.scopes.some(scope => pixelScopes.has(scope)) ? 'px' : ''}`;
  }
  throw new Error(`变量类型或值无效：${token.name} (${token.type})`);
}

async function readSources(sourceDir) {
  const files = await findFiles(sourceDir, '.tokens.json');
  if (!files.length) throw new Error('source 中没有找到 .tokens.json 文件');
  const sources = [];
  for (const file of files) {
    const relativePath = path.relative(sourceDir, file);
    try {
      const source = parseSourcePath(relativePath);
      source.tokens = collectTokens(JSON.parse(await readFile(file, 'utf8')));
      if (!source.tokens.length) throw new Error('文件中没有变量');
      const names = new Set();
      for (const token of source.tokens) {
        if (names.has(token.name)) throw new Error(`重复的 CSS 变量：${token.name}`);
        names.add(token.name);
        if (['primitive', 'semantic'].includes(source.kind) && token.type !== 'color') {
          throw new Error(`颜色文件不支持 ${token.type} 变量：${token.name}`);
        }
      }
      sources.push(source);
    } catch (error) {
      throw new Error(`${relativePath}：${error.message}`);
    }
  }
  return sources;
}

function renderBlock(theme, title, tokens, defaultTheme) {
  const selector = `html[theme='${theme}']`;
  const lines = [
    `${theme === defaultTheme ? `html:not([theme]),\n${selector}` : selector} {`,
    '  /* ============================================',
    `   * ${title}`,
    `   * ${generatedNotice}`,
    '   * ============================================ */',
  ];
  let previousGroup;
  for (const token of tokens) {
    const group = token.name.replace(/-(?:size|line-height)$/, '').replace(/-\d+$/, '');
    if (previousGroup && previousGroup !== group) lines.push('');
    lines.push(`  ${token.name}: ${token.value};`);
    previousGroup = group;
  }
  return [...lines, '}', ''].join('\n');
}

async function readDefaultTheme(sourceDir) {
  const file = path.join(sourceDir, 'themes.config.json');
  const text = await readFile(file, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return '{}';
    throw error;
  });
  try {
    const config = JSON.parse(text);
    if (!config || typeof config !== 'object' || Array.isArray(config)) throw new Error('配置必须是对象');
    if (config.defaultTheme !== undefined && typeof config.defaultTheme !== 'string') {
      throw new Error('defaultTheme 必须是主题名称');
    }
    return config.defaultTheme;
  } catch (error) {
    throw new Error(`themes.config.json：${error.message}`);
  }
}

function renderImports(files) {
  return [`/* ${generatedNotice} */`, ...files.map(file => `@import './${file.split(path.sep).join('/')}';`), ''].join('\n');
}

export async function buildThemeFiles({ sourceDir = defaultSourceDir } = {}) {
  const sources = await readSources(sourceDir);
  const outputs = new Map();
  const namesByTheme = new Map();
  const primitives = new Map();
  const typography = new Map();
  const themes = new Set(sources.map(source => source.theme).filter(theme => theme !== null));
  const defaultTheme = await readDefaultTheme(sourceDir);
  if (defaultTheme !== undefined && !themes.has(defaultTheme)) {
    throw new Error(`默认主题不存在：${defaultTheme}`);
  }

  function addOutput(theme, relativePath, title, tokens) {
    if (outputs.has(relativePath)) throw new Error(`多个源文件映射到同一个 CSS 文件：${relativePath}`);
    const names = namesByTheme.get(theme) ?? new Set();
    for (const token of tokens) {
      if (names.has(token.name)) throw new Error(`重复的 CSS 变量：${theme}/${token.name}`);
      names.add(token.name);
    }
    namesByTheme.set(theme, names);
    outputs.set(relativePath, renderBlock(theme, title, tokens, defaultTheme));
  }

  // 先建立完整的 primitive 索引，引用解析不依赖源文件遍历顺序。
  for (const source of sources.filter(source => source.kind === 'primitive')) {
    const { theme, name, relativePath } = source;
    const tokens = source.tokens.map(token => {
      try { return { name: `--theme-color-${token.name}`, value: colorToCss(token.value) }; }
      catch (error) { throw new Error(`${relativePath}/${token.name}：${error.message}`); }
    });
    const title = theme.charAt(0).toUpperCase() + theme.slice(1);
    addOutput(theme, path.join(theme, 'primitive', `${name}.css`), `Primitive Color Tokens — ${title} Theme`, tokens);
    primitives.set(theme, new Map([...(primitives.get(theme) ?? []), ...tokens.map(token => [token.name, token])]));
  }

  for (const source of sources.filter(source => source.kind === 'semantic')) {
    const { theme, name, relativePath } = source;
    const tokens = source.tokens.map(token => {
      const alias = token.alias;
      if (!alias?.targetVariableName || !/^Primitives?(?:\s*\/|$)/i.test(alias.targetVariableSetName ?? '')) {
        throw new Error(`${relativePath}：缺少 primitive 引用：${token.name}`);
      }
      const target = `--theme-color-${normalizeName(alias.targetVariableName)}`;
      if (!primitives.get(theme)?.has(target)) throw new Error(`${relativePath}：找不到 ${theme} 的 primitive：${target}`);
      return { name: `--color-${token.name}`, value: `var(${target})` };
    });
    addOutput(theme, path.join(theme, 'semantic', `${name}.css`), `Semantic Color Tokens — ${theme} Theme`, tokens);
  }

  for (const source of sources.filter(source => source.kind === 'typography')) {
    const tokens = typography.get(source.theme) ?? new Map();
    for (const token of source.tokens) {
      const name = `--${token.name === 'font-family-text' ? `font-family-${source.name}` : token.name}`;
      const value = scalarToCss(token);
      if (tokens.has(name) && tokens.get(name).value !== value) {
        throw new Error(`${source.relativePath}：字体模式的共用设置不一致：${name}`);
      }
      tokens.set(name, { name, value });
    }
    typography.set(source.theme, tokens);
  }
  if (typography.size && !themes.size) throw new Error('没有找到字体输出对应的主题');
  for (const theme of themes) {
    const merged = new Map([...(typography.get(null) ?? []), ...(typography.get(theme) ?? [])]);
    if (!merged.size) continue;
    const tokens = [...merged.values()];
    const fonts = tokens.filter(token => token.name.startsWith('--font-family-'));
    const shared = tokens.filter(token => !token.name.startsWith('--font-family-'));
    addOutput(theme, path.join(theme, 'semantic/typography.css'), `Semantic Typography Tokens — ${theme} Theme`, [...fonts, ...shared]);
  }

  const radii = new Map();
  for (const source of sources.filter(source => source.kind === 'radius')) {
    if (radii.has(source.theme)) throw new Error(`${source.relativePath}：重复的圆角文件`);
    radii.set(source.theme, source);
  }
  if (radii.size && !themes.size) throw new Error('没有找到圆角输出对应的主题');
  for (const theme of themes) {
    const source = radii.get(theme) ?? radii.get(null);
    if (!source) continue;
    const tokens = source.tokens.map(token => {
      if (token.type !== 'number' || !Number.isFinite(token.value) || token.value < 0) {
        throw new Error(`${source.relativePath}：圆角必须是非负数字：${token.name}`);
      }
      return { name: `--radius-${token.name}`, value: `${token.value}px` };
    });
    addOutput(theme, path.join(theme, 'semantic/radius.css'), `Semantic Radius Tokens — ${theme} Theme`, tokens);
  }
  const orderedThemes = [
    ...(defaultTheme === undefined ? [] : [defaultTheme]),
    ...[...themes].filter(theme => theme !== defaultTheme).sort(),
  ];
  for (const theme of orderedThemes) {
    const files = [...outputs.keys()].filter(file => file.startsWith(theme + path.sep))
      .map(file => path.relative(theme, file)).sort();
    outputs.set(path.join(theme, 'index.css'), renderImports(files));
  }
  outputs.set('index.css', renderImports(orderedThemes.map(theme => path.join(theme, 'index.css'))));
  return outputs;
}

export async function generateThemes({
  sourceDir = defaultSourceDir, targetDir = defaultTargetDir, check = false, quiet = false,
} = {}) {
  // 完成解析和校验后才允许写文件。
  const outputs = await buildThemeFiles({ sourceDir });
  if (check) {
    const differences = [];
    for (const [relativePath, css] of outputs) {
      const current = await readFile(path.join(targetDir, relativePath), 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
      });
      if (current !== css) differences.push(`${current === null ? '缺失' : '内容不同'}：${relativePath}`);
    }
    for (const file of await findFiles(targetDir, '.css', true)) {
      const relativePath = path.relative(targetDir, file);
      if (!outputs.has(relativePath) && (await readFile(file, 'utf8')).includes(generatedNotice)) {
        differences.push(`多余文件：${relativePath}`);
      }
    }
    if (differences.length) throw new Error(`主题文件与 source 不一致：\n${differences.join('\n')}`);
    if (!quiet) console.log(`校验通过：${outputs.size} 个 CSS 文件与 source 生成结果逐字节一致。`);
  } else {
    for (const [relativePath, css] of outputs) {
      const target = path.join(targetDir, relativePath);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, css, 'utf8');
      if (!quiet) console.log(path.relative(projectRoot, target));
    }
  }
  return [...outputs.keys()].map(relativePath => path.join(targetDir, relativePath));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const unknown = args.filter(arg => arg !== '--check');
  if (unknown.length) {
    console.error(`未知参数：${unknown.join(' ')}`);
    process.exitCode = 1;
  } else {
    generateThemes({ check: args.includes('--check') }).catch(error => {
      console.error(`转换失败：${error.message}`);
      process.exitCode = 1;
    });
  }
}
