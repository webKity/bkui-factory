import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import tailwindcss from '@tailwindcss/postcss';

const directory = new URL('../packages/ui-react/src/components/typography/', import.meta.url);
const from = fileURLToPath(new URL('entry.css', directory));
const output = new URL('plugin.css', directory);
const result = await postcss([tailwindcss({ optimize: false })]).process(`
@config './plugin.config.cjs';
@source inline('bk-typography');
@tailwind utilities source(none);
`, { from });
const css = `/* Generated by npm run typography:build; do not edit. */\n${result.css}`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== css) throw new Error('Typography CSS 已过期，请执行 npm run typography:build');
} else {
  await writeFile(output, css);
}
