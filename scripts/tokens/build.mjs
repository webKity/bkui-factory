import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { findFiles, quoteCssString, buildTokenModel } from './source.mjs';

const projectRoot = fileURLToPath(new URL('../../', import.meta.url));
const defaultSourceDir = path.join(projectRoot, 'source');
const defaultTargetDir = path.join(projectRoot, 'packages/ui-react/src/components/themes');
const notice = 'Generated by npm run tokens:build; do not edit.';

function renderBlock(theme, title, tokens, defaultTheme) {
  const selector = `html[theme='${theme}']`;
  const lines = [
    `${theme === defaultTheme ? `html:not([theme]),\n${selector}` : selector} {`,
    '  /* ============================================',
    `   * ${title}`,
    `   * ${notice}`,
    '   * ============================================ */',
  ];
  let previousGroup;
  for (const token of tokens) {
    const group = token.name.replace(/-(?:size|line-height)$/, '').replace(/-\d+$/, '');
    if (previousGroup && previousGroup !== group) lines.push('');
    lines.push(`  ${token.name}: ${token.value};`);
    previousGroup = group;
  }
  return [...lines, '}', ''].join('\n');
}

function renderImports(files) {
  return [`/* ${notice} */`, ...files.map(file => `@import './${file.split(path.sep).join('/')}';`), ''].join('\n');
}

export async function buildThemeFiles({ sourceDir = defaultSourceDir, model } = {}) {
  model ??= await buildTokenModel({ sourceDir, components: false });
  const outputs = new Map();
  const namesByTheme = new Map();
  const sources = model.sources;
  const defaultTheme = model.configuredDefaultTheme;
  function addOutput(theme, relativePath, title, tokens) {
    if (outputs.has(relativePath)) throw new Error(`多个源文件映射到同一个 CSS 文件：${relativePath}`);
    const names = namesByTheme.get(theme) ?? new Set();
    for (const token of tokens) {
      if (names.has(token.name)) throw new Error(`重复的 CSS 变量：${theme}/${token.name}`);
      names.add(token.name);
    }
    namesByTheme.set(theme, names);
    outputs.set(relativePath, renderBlock(theme, title, tokens, defaultTheme));
  }
  function cssValue(token) {
    if (token.ref) return `var(--theme-color-${token.ref.slice('primitive.'.length)})`;
    if (token.type === 'string') return quoteCssString(token.value);
    return `${token.value}${token.type === 'dimension' ? 'px' : ''}`;
  }
  for (const [theme, data] of Object.entries(model.themes)) {
    for (const source of sources.filter(source => source.theme === theme && ['primitive', 'semantic'].includes(source.kind))) {
      const primitive = source.kind === 'primitive';
      const tokens = source.tokens.map(token => {
        const id = primitive ? `primitive.${token.name}` : `semantic.color-${token.name}`;
        return { name: primitive ? `--theme-color-${token.name}` : `--color-${token.name}`, value: cssValue(data.tokens.get(id)) };
      });
      const title = primitive ? `Primitive Color Tokens — ${theme.charAt(0).toUpperCase() + theme.slice(1)} Theme` : `Semantic Color Tokens — ${theme} Theme`;
      addOutput(theme, path.join(theme, primitive ? 'primitive' : 'semantic', `${source.name}.css`), title, tokens);
    }
    const typography = [...data.tokens].filter(([id]) => id.startsWith('semantic.') && !id.startsWith('semantic.color-') && !id.startsWith('semantic.radius-'))
      .map(([id, token]) => ({ name: `--${id.slice(9)}`, value: cssValue(token) }));
    if (typography.length) {
      const fonts = typography.filter(token => token.name.startsWith('--font-family-'));
      const shared = typography.filter(token => !token.name.startsWith('--font-family-'));
      addOutput(theme, path.join(theme, 'semantic/typography.css'), `Semantic Typography Tokens — ${theme} Theme`, [...fonts, ...shared]);
    }
    const radii = [...data.tokens].filter(([id]) => id.startsWith('semantic.radius-')).map(([id, token]) => ({ name: `--${id.slice(9)}`, value: cssValue(token) }));
    if (radii.length) addOutput(theme, path.join(theme, 'semantic/radius.css'), `Semantic Radius Tokens — ${theme} Theme`, radii);
  }
  const themes = Object.keys(model.themes);
  const orderedThemes = [...(defaultTheme === undefined ? [] : [defaultTheme]), ...themes.filter(theme => theme !== defaultTheme).sort()];
  for (const theme of orderedThemes) {
    const files = [...outputs.keys()].filter(file => file.startsWith(theme + path.sep)).map(file => path.relative(theme, file)).sort();
    outputs.set(path.join(theme, 'index.css'), renderImports(files));
  }
  outputs.set('index.css', renderImports(orderedThemes.map(theme => path.join(theme, 'index.css'))));
  return outputs;
}

export async function generateThemes({
  sourceDir = defaultSourceDir, targetDir = defaultTargetDir, check = false, quiet = false,
} = {}) {
  // 完成解析和校验后才允许写文件。
  const outputs = await buildThemeFiles({ sourceDir });
  if (check) {
    const differences = [];
    for (const [relativePath, css] of outputs) {
      const current = await readFile(path.join(targetDir, relativePath), 'utf8').catch(error => {
        if (error.code === 'ENOENT') return null;
        throw error;
      });
      if (current !== css) differences.push(`${current === null ? '缺失' : '内容不同'}：${relativePath}`);
    }
    for (const file of await findFiles(targetDir, '.css', true)) {
      const relativePath = path.relative(targetDir, file);
      if (!outputs.has(relativePath) && (await readFile(file, 'utf8')).includes(notice)) {
        differences.push(`多余文件：${relativePath}`);
      }
    }
    if (differences.length) throw new Error(`主题文件与 source 不一致：\n${differences.join('\n')}`);
    if (!quiet) console.log(`校验通过：${outputs.size} 个 CSS 文件与 source 生成结果逐字节一致。`);
  } else {
    for (const [relativePath, css] of outputs) {
      const target = path.join(targetDir, relativePath);
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, css, 'utf8');
      if (!quiet) console.log(path.relative(projectRoot, target));
    }
  }
  return [...outputs.keys()].map(relativePath => path.join(targetDir, relativePath));
}


function cssComponentPath(id) {
  const [, component, section, ...parts] = id.split('.');
  if (section === 'base') return `--${component}-${parts.join('-')}`;
  if (section === 'sizes') return `--${component}-size-${parts.join('-')}`;
  if (section === 'intents') return `--${component}-${parts.slice(1).join('-')}`;
  throw new Error(`不支持的组件分组：${id}，支持 base / sizes / intents`);
}
function cssRef(id) {
  if (id.startsWith('primitive.')) return `--theme-color-${id.slice(10)}`;
  if (id.startsWith('semantic.')) return `--${id.slice(9)}`;
  return cssComponentPath(id);
}
function emitComponentCss(model) {
  const first = Object.values(model.themes)[0];
  const outputs = new Map();
  for (const component of Object.keys(model.componentDefinitions)) {
    const groups = new Map();
    const namesBySelector = new Map();
    for (const [id, token] of first.tokens) {
      if (!id.startsWith(`components.${component}.`)) continue;
      const parts = id.split('.');
      const selector = `.bkreact-${component}` + (parts[2] === 'intents' ? `:where([data-intent='${parts[3]}'])` : '');
      const name = cssComponentPath(id);
      const names = namesBySelector.get(selector) ?? new Set();
      if (names.has(name)) throw new Error(`重复组件 CSS 变量：${selector}/${name}`);
      names.add(name); namesBySelector.set(selector, names);
      // Component aliases within an intent can resolve differently after merging;
      // reject ambiguous cross-section aliases rather than silently generating stale native values.
      if (token.ref?.startsWith('components.') && token.ref.split('.')[2] === 'intents') throw new Error(`不能引用 intent 局部变量：${id}`);
      const value = token.ref ? `var(${cssRef(token.ref)})` : token.type === 'dimension' ? `${token.value}px` : token.type === 'string' ? quoteCssString(token.value) : token.value;
      const lines = groups.get(selector) ?? [];
      lines.push(`  ${name}: ${value};`); groups.set(selector, lines);
    }
    outputs.set(`packages/ui-react/src/components/${component}/design.tokens.css`, `/* ${notice} */\n` + [...groups].map(([selector, lines]) => `${selector} {\n${lines.join('\n')}\n}\n`).join('\n'));
  }
  return outputs;
}

function emitNativeFiles(model) {
  const outputs = new Map();
  const base = 'packages/ui-native/src/components';
  // Global theme data contains foundations only. Components own their generated values.
  const themes = Object.fromEntries(Object.entries(model.themes).map(([name, data]) => [name, {
    primitive: data.native.primitive,
    semantic: data.native.semantic,
  }]));
  const dimensions = [...new Set(Object.values(model.themes).flatMap(data => [...data.tokens]
    .filter(([id, token]) => id.startsWith('semantic.') && token.type === 'dimension')
    .map(([id]) => id.slice('semantic.'.length))))];
  const themeSource = [
    `// ${notice}`,
    `export const themes = ${JSON.stringify(themes, null, 2)};`,
    'export type ThemeName = keyof typeof themes;',
    'export type NativeTheme = typeof themes[ThemeName];',
    `export const defaultTheme: ThemeName = ${JSON.stringify(model.defaultTheme)};`,
    '',
    `const dimensions = new Set(${JSON.stringify(dimensions)});`,
    'export const themeVariables = Object.fromEntries(',
    '  Object.entries(themes).map(([name, theme]) => [name, Object.fromEntries(',
    '    Object.entries(theme.semantic).map(([key, value]) => [',
    '      `--bk-semantic-${key}`, dimensions.has(key) ? `${value}px` : value,',
    '    ]),',
    '  )]),',
    ') as Record<ThemeName, Record<`--${string}`, string | number>>;',
    '',
  ].join('\n');
  outputs.set(`${base}/themes/tokens.ts`, themeSource);
  for (const component of Object.keys(model.componentDefinitions)) {
    const values = Object.fromEntries(Object.entries(model.themes).map(([name, data]) => [name, data.native.components[component]]));
    outputs.set(`${base}/${component}/design.tokens.ts`, `// ${notice}\nexport const tokens = ${JSON.stringify(values, null, 2)};\n`);
  }
  const declarations = [];
  const utilities = [];
  const data = model.themes[model.defaultTheme];
  for (const [id, token] of data.tokens) {
    if (!id.startsWith('semantic.')) continue;
    const name = `--bk-${id.replaceAll('.', '-')}`;
    const value = data.resolved.get(id);
    declarations.push(`  ${name}: ${token.type === 'string' ? quoteCssString(value) : token.type === 'dimension' ? `${value}px` : value};`);
    if (id.startsWith('semantic.color-')) {
      utilities.push(`  --color-bk-${id.slice('semantic.color-'.length)}: var(${name});`);
    } else if (id.startsWith('semantic.radius-')) {
      utilities.push(`  --radius-bk-${id.slice('semantic.radius-'.length)}: var(${name});`);
    } else if (/^semantic\.text-.+-size$/.test(id)) {
      const size = id.slice('semantic.text-'.length, -'-size'.length);
      utilities.push(`  --text-bk-${size}: var(${name});`);
      if (data.tokens.has(`semantic.text-${size}-line-height`)) utilities.push(`  --text-bk-${size}--line-height: var(--bk-semantic-text-${size}-line-height);`);
    }
  }
  outputs.set(`${base}/themes/tokens.css`, `/* ${notice} */\n:root {\n${declarations.join('\n')}\n}\n\n@theme inline {\n${utilities.join('\n')}\n}\n`);
  return outputs;
}

export async function buildTokenFiles({ sourceDir = defaultSourceDir } = {}) {
  // Validate the complete graph before any platform files are written.
  const model = await buildTokenModel({ sourceDir });
  const outputs = new Map();
  for (const [name, contents] of await buildThemeFiles({ sourceDir, model })) {
    outputs.set(`packages/ui-react/src/components/themes/${name}`, contents);
  }
  for (const [name, contents] of emitComponentCss(model)) outputs.set(name, contents);
  for (const [name, contents] of emitNativeFiles(model)) outputs.set(name, contents);
  return outputs;
}

export async function generateTokens({ check = false, sourceDir, targetRoot = projectRoot, quiet = false } = {}) {
  const outputs = await buildTokenFiles({ sourceDir });
  const differences = [];
  for (const [name, contents] of outputs) {
    const target = path.join(targetRoot, name);
    if (check) {
      const current = await readFile(target, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
      if (current !== contents) differences.push(`${current === null ? '缺失' : '内容不同'}：${name}`);
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, contents);
    }
  }
  if (check) {
    for (const dir of ['packages/ui-react/src/components', 'packages/ui-native/src/components']) {
      for (const file of await findFiles(path.join(targetRoot, dir), '', true)) {
        const relative = path.relative(targetRoot, file);
        if (outputs.has(relative)) continue;
        if ((await readFile(file, 'utf8')).includes(notice)) differences.push(`多余文件：${relative}`);
      }
    }
    if (differences.length) throw new Error(differences.join('\n'));
  }
  if (!quiet) console.log(`${check ? '校验' : '生成'} ${outputs.size} 个 Web / RN token 文件`);
  return outputs;
}
